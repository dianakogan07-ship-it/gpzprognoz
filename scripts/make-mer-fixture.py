SUB = {2026: (480, 540), 2027: (600, 660), 2028: (720, 780)}

def ct(x, y, s, size):
    c.setFont("DV", size); c.drawCentredString(x, y, s)

def header(y):
    t(40, y, "Показатель", 9)
    ct(368, y, "2024", 9); ct(433, y, "2025", 9)
    for yr, (b, k) in SUB.items():
        ct((b + k) / 2 - 11, y, str(yr), 9)
    ct(368, y - 12, "отчет", 8); ct(433, y - 12, "оценка", 8)
    for yr, (b, k) in SUB.items():
        ct(b - 11, y - 12, "базовый", 8); ct(k - 11, y - 12, "консерв.", 8)
    return y - 30

def vals(y, nums):
    xs = [379, 444] + [v for yr in (2026, 2027, 2028) for v in SUB[yr]]
    for x, n in zip(xs, nums):
        t(x, y, n, 9, right=True)

