/** Федеральные округа по первым двум цифрам кода ОКАТО региона */
const BY_PREFIX: Record<string, string> = {};
const D: [string, string[]][] = [
  ["Центральный", ["14", "15", "17", "20", "24", "28", "29", "34", "38", "42", "45", "46", "54", "61", "66", "68", "70", "78"]],
  ["Северо-Западный", ["11", "19", "27", "40", "41", "47", "49", "58", "86", "87"]],
  ["Южный", ["03", "12", "18", "35", "60", "67", "79", "85"]],
  ["Северо-Кавказский", ["07", "26", "82", "83", "90", "91", "96"]],
  ["Приволжский", ["22", "33", "36", "53", "56", "57", "63", "73", "80", "88", "89", "92", "94", "97"]],
  ["Уральский", ["37", "65", "71", "75"]],
  ["Сибирский", ["01", "04", "25", "32", "50", "52", "69", "84", "93", "95"]],
  ["Дальневосточный", ["05", "08", "10", "30", "44", "64", "76", "77", "81", "98", "99"]],
];
for (const [name, codes] of D) for (const c of codes) BY_PREFIX[c] = name;
export const DISTRICTS = D.map(([n]) => n);

export function districtOf(region: string | null): string | null {
  return region ? BY_PREFIX[region.slice(0, 2)] ?? null : null;
}
